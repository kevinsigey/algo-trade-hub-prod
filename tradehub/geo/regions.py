"""Chokepoint regions as CONFIG (Kevin's plan, 2026-11-02): every region is a
bounding box -> transit gates -> anchorages -> terminal footprints, and the
same metric families are computed for each. Baselines are trailing 14-30d
medians from our own snapshots, never a pre-crisis 'normal'.

Boxes are (lat_min, lon_min, lat_max, lon_max)."""

from __future__ import annotations

from dataclasses import dataclass, field


def inside(box: tuple[float, float, float, float], lat: float, lon: float) -> bool:
    return box[0] <= lat <= box[2] and box[1] <= lon <= box[3]


@dataclass(frozen=True)
class Region:
    slug: str
    title: str
    bbox: tuple[float, float, float, float]          # the display area
    ais_boxes: tuple[tuple[float, float, float, float], ...]  # subscription union
    gate: tuple[float, float, float, float]          # the transit gate
    anchorages: dict[str, tuple[float, float, float, float]]
    terminals: dict[str, tuple[float, float, float, float]]   # FIRMS footprints
    quake_bbox: tuple[float, float, float, float]
    gpsjam_hexes: frozenset[str] = field(default_factory=frozenset)


