"""The hub-wide test registry (Kevin, 2026-11-03).

A PASS used to be judged against each idea's own reruns only: run an idea
once and the bar was p < 0.05, so 42 of 53 ideas passed. Standing is now
judged against every test the hub has run:

- a Benjamini-Hochberg FDR bar (q = 0.05) over the family of every idea's
  latest saved run -- a hub-wide Bonferroni bar is unreachable at 1,000
  permutations (0.05/63 < 1/1001), FDR is the honest adjustment;
- p at or under 0.01 (Kevin, 2026-11-03): 26 ideas tie at the shuffle's floor
  of 0.001, and that pile loosened the FDR bar to about p = 0.036; and
- the claim must have held in at least 3 of 4 walk-forward folds.

Pure functions over run rows; the API layer feeds them and consumers
(the Ideas record, the go-live gate, tracking) read the adjusted verdict.
The stored per-run verdict never changes -- this is the current standing.
"""

from __future__ import annotations

import re

FDR_Q = 0.05
P_MAX = 0.01
WF_MIN_SHARE = 0.75

_LAB_RE = re.compile(r"random lab|lab\s?gated|lab\d|sweep survivor", re.IGNORECASE)


def wf_ok(walk_forward: dict | None) -> bool:
    """The claim held in at least 3 of 4 judged walk-forward folds.
    No judged folds means durability is unverifiable, not fine."""
    if not walk_forward or not walk_forward.get("of"):
        return False
    return walk_forward["held"] >= WF_MIN_SHARE * walk_forward["of"]


def bh_rejected(pvals: list[float], q: float = FDR_Q) -> set[int]:
    """Indices rejected by Benjamini-Hochberg at FDR q."""
    order = sorted(range(len(pvals)), key=lambda i: pvals[i])
    kmax = 0
    for k, i in enumerate(order, 1):
        if pvals[i] <= (k / len(pvals)) * q:
            kmax = k
    return {order[i] for i in range(kmax)}


def adjusted(latest_by_idea: dict[int, dict]) -> dict[int, dict]:
    """Each idea's current standing under the hub-wide standard.

    Input: idea id -> its latest SAVED run row (verdict + result). A stored
    PASS is demoted when its p fails the FDR bar or P_MAX, or its walk-forward
    falls short; every other verdict stands as stored."""
    def _p(run: dict):
        return ((run.get("result") or {}).get("shuffle") or {}).get("p")

    fam_ids = [iid for iid, r in latest_by_idea.items() if _p(r) is not None]
    rejected = bh_rejected([float(_p(latest_by_idea[i])) for i in fam_ids])
    fdr = {iid: (pos in rejected) for pos, iid in enumerate(fam_ids)}
    out: dict[int, dict] = {}
    for iid, run in latest_by_idea.items():
        result = run.get("result") or {}
        if result.get("battery"):
            # A claim-typed battery run (spec 2026-11-08): the BH family above is defined
            # over timing shuffle p-values, so a battery verdict stands as stored —
            # reported, never demoted here — until a cross-battery FDR treatment is
            # preregistered. The run still counts in store.insert_run's family log.
            out[iid] = {"verdict_now": run.get("verdict"), "fdr_pass": None, "p_ok": None,
                        "wf_ok": None, "p": None, "battery": result["battery"].get("type")}
            continue
        wf = result.get("walk_forward")
        ok_wf = wf_ok(wf)
        verdict = run.get("verdict")
        now = verdict
        p = _p(run)
        ok_p = None if p is None else float(p) <= P_MAX
        if verdict == "PASS" and (fdr.get(iid) is not True or not ok_wf or not ok_p):
            now = "FAIL"
        out[iid] = {"verdict_now": now, "fdr_pass": fdr.get(iid), "p_ok": ok_p,
                    "wf_ok": ok_wf if wf is not None else None, "p": _p(run)}
    return out


def families(holdings: dict[int, set[str]]) -> dict[int, dict]:
    """Group ideas that bet on the same names (union-find over shared
    tickers): five wrappers on MU/TXN/TSM are one bet, not five."""
    parent = {i: i for i in holdings}

    def find(x: int) -> int:
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    by_ticker: dict[str, int] = {}
    for iid, tickers in holdings.items():
        for t in tickers:
            if t in by_ticker:
                a, b = find(iid), find(by_ticker[t])
                if a != b:
                    parent[max(a, b)] = min(a, b)
            else:
                by_ticker[t] = iid
    groups: dict[int, list[int]] = {}
    for iid in holdings:
        groups.setdefault(find(iid), []).append(iid)
    out: dict[int, dict] = {}
    for root, members in groups.items():
        tickers = sorted(set().union(*(holdings[m] for m in members))) if members else []
        for m in members:
            out[m] = {"key": root, "size": len(members), "tickers": tickers,
                      "members": sorted(members)}
    return out


def origin_of(idea: dict, screen_idea_ids: set[int]) -> str:
    """Where an idea came from, from its own record: promoted out of a
    screen, generated by a strategy-lab sweep, or written by hand."""
    if idea.get("id") in screen_idea_ids:
        return "screen"
    text = f"{idea.get('title') or ''} {idea.get('plain_words') or ''}"
    return "lab" if _LAB_RE.search(text) else "manual"


def hindsight_selected(origin: str) -> bool:
    """Picked after seeing how the names did -- a lab sweep over known
    history or a screen over today's data -- then backtested on the past.
    The selection knew the answer; the label says so."""
    return origin in {"lab", "screen"}
