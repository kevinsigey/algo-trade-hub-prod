"""Exports REGISTRY (+ universe builders + filter ops) to catalog.json/.md."""

from __future__ import annotations

import json
from pathlib import Path

from .functions import REGISTRY
from .universes import UNIVERSE_BUILDERS

OPS = [
    {"op": "lt", "doc": "field < value (numeric)"},
    {"op": "le", "doc": "field <= value (numeric)"},
    {"op": "gt", "doc": "field > value (numeric)"},
    {"op": "ge", "doc": "field >= value (numeric)"},
    {"op": "eq", "doc": "field == value (numeric or string)"},
    {"op": "ne", "doc": "field != value (numeric or string)"},
    {"op": "between", "doc": "lo <= field <= hi; value = [lo, hi]"},
    {"op": "in", "doc": "field is one of value (list; for string fields like sector)"},
    {"op": "pct_gte", "doc": "field's cross-sectional percentile >= value (0-100)"},
    {"op": "pct_lte", "doc": "field's cross-sectional percentile <= value (0-100)"},
]


def catalog_dict() -> dict:
    fns = []
    for name in sorted(REGISTRY):
        e = REGISTRY[name]
        fns.append({"name": e["name"], "category": e["category"],
                    "kind": e["kind"], "params": e["params"],
                    "returns": e["returns"], "doc": e["doc"],
                    "source": e["source"]})
    return {"functions": fns, "universe_builders": UNIVERSE_BUILDERS, "ops": OPS}


def write_catalog(out_dir: str | Path) -> tuple[Path, Path]:
    out_dir = Path(out_dir)
    data = catalog_dict()
    jp = out_dir / "catalog.json"
    jp.write_text(json.dumps(data, indent=2))

    lines = ["# Screening Function Catalog", "",
             "Generated by `build_catalog.py` from the function registry. "
             "Every function lists its params (with defaults), what it returns, "
             "and the data source behind it — this is the menu the future Hub "
             "Screening tab renders as UI controls, and the vocabulary an AI "
             "uses when it emits a query spec.", ""]
    lines.append("## Universe builders")
    for b in data["universe_builders"]:
        lines.append(f"- **{b['name']}** (`type: {b['type']}`) — {b['doc']}")
    lines.append("")
    lines.append("## Filter ops")
    for o in data["ops"]:
        lines.append(f"- `{o['op']}` — {o['doc']}")
    lines.append("")
    by_cat: dict[str, list] = {}
    for f in data["functions"]:
        by_cat.setdefault(f["category"], []).append(f)
    for cat in sorted(by_cat):
        lines.append(f"## {cat}")
        lines.append("")
        lines.append("| Function | Returns | Params | Source | What it does |")
        lines.append("|---|---|---|---|---|")
        for f in by_cat[cat]:
            ps = ", ".join(f"{k}={v['default']!r}" for k, v in f["params"].items()) or "—"
            lines.append(f"| `{f['name']}` | {f['returns']} | {ps} | "
                         f"{f['source']} | {f['doc']} |")
        lines.append("")
    mp = out_dir / "catalog.md"
    mp.write_text("\n".join(lines))
    return jp, mp
